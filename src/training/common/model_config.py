"""`PolicyValueNet`のネットワーク構成。PPO/MCTSで共有し、チェックポイントを
相互に使い回せるようにする(定義箇所を1つに保つことで、サイズを変えるときの修正漏れを防ぐ)。
"""

# 手札を何トークンで表すか。1なら全カードのone-hotを1トークンに合算する(公式サンプルと同じ)。
# 2以上ならカードIDの昇順に1枚ずつ別トークンへ置き、溢れた分を最後のトークンへ合算する。
# 実測では手札は平均6.7枚(ユニーク5.4種)あり、1トークンに潰すとエンコーダが個々の
# 手札カードへ注意を向けられない。一方ベンチは8枠中平均3.6枠しか埋まっておらず、
# 26トークンの割り当てが実態と合っていない。
HAND_TOKENS = 12

# ベンチの枠数。実測では全20,588局面で`benchMax = 5`(ルール上も5枠)。
BENCH_SLOTS = 5

# 容量診断では当てはめ残差がほぼ0で、表現力は律速ではなかった。一方MCTSラップ推論は
# 探索回数がそのまま強さに効くため、余った容量は探索深さへ回す方が期待値が高い。
# 層のパラメータはD_MODELの二乗で効くので、256→128で計算量はおよそ1/4になる。
D_MODEL = 128
NUM_HEADS = 4
# 512から1024へ広げた。当時は「容量不足」と判断したが、その根拠は誤りだった
# (検証セットが学習期間の内側にあり、汎化性能を過大評価していた。測り直すと
# 512の時点で既に train損失 < val損失 で、容量不足ではなかった)。
# それでも1024を維持しているのは、ラダーで実測 +68点(945.7→1014.1 / 937.3→1005.5)
# だったため。ただしこの実測はデータを11日→28日に増やした変更と同時なので、
# 容量とデータのどちらが効いたかは分離できていない。
#
# 広げる先にFFNを選んだ理由は推論コスト。D_MODELを上げると注意機構もトークン埋め込みも
# 巻き込んで推論が約2倍になり、実測で+73.6点を稼いでいる探索回数を半減させる羽目になる。
# FFNの拡張なら増えるのは行列積2つぶんで済む。
D_FEEDFORWARD = 1024
# 速度は制約になっていない(5+5でも1試合が持ち時間600秒の2%程度)。一方この重みは
# 後続の学習の初期値にもなるため、容量不足だと層を増やした時点でチェックポイントが
# 使えなくなり、ゼロからやり直しになる。足りない場合の損失の方が大きいので余裕を取る。
NUM_LAYERS_ENCODER = 4
NUM_LAYERS_DECODER = 4

# デコーダ層に行動どうしの自己注意を入れるか。
# Falseだと各行動が独立に盤面へ交差注意するだけで、行動どうしは最後のsoftmaxまで
# 相互作用しない。「Xが打てるなら手札を温存する」のような、選択肢集合に依存する
# 判断が表現しにくい。位置埋め込みを持たない自己注意は順序不変なので、
# 列挙順に結果が依存しない性質は保たれる。
DECODER_SELF_ATTENTION = True

# 自己対戦は毎ラウンド新しいデータなので0で問題なかったが、BCは固定データセットを
# 何エポックも回すため過学習する(実測: 3エポックでvalue_lossが訓練0.22/検証1.15)。
# dropout層はパラメータを持たないので、既存チェックポイントとの互換性は保たれる。
DROPOUT = 0.1
